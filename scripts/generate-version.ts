import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const repositoryRoot = fileURLToPath(new URL('../', import.meta.url));
const packagePath = fileURLToPath(new URL('../package.json', import.meta.url));
const outputPath = fileURLToPath(
  new URL('../src/infrastructure/generated/version.ts', import.meta.url),
);
const checkOnly = process.argv.includes('--check');

const packageMetadata: unknown = JSON.parse(await readFile(packagePath, 'utf8'));
const require = createRequire(import.meta.url);
const playwrightPackagePath = require.resolve('playwright/package.json');
const playwrightMetadata: unknown = JSON.parse(await readFile(playwrightPackagePath, 'utf8'));
if (
  typeof packageMetadata !== 'object' ||
  packageMetadata === null ||
  !('version' in packageMetadata) ||
  typeof packageMetadata.version !== 'string' ||
  !/^[0-9A-Za-z.+-]+$/u.test(packageMetadata.version)
) {
  throw new Error('package.json must contain a safe SemVer-compatible version');
}
if (
  typeof playwrightMetadata !== 'object' ||
  playwrightMetadata === null ||
  !('version' in playwrightMetadata) ||
  typeof playwrightMetadata.version !== 'string' ||
  !/^[0-9A-Za-z.+-]+$/u.test(playwrightMetadata.version)
) {
  throw new Error('Resolved playwright package must contain a safe version');
}

const generated =
  `// Generated by scripts/generate-version.ts from resolved package metadata. Do not edit.\n` +
  `// x-release-please-start-version\n` +
  `export const BROWSERMESH_VERSION = '${packageMetadata.version}' as const;\n` +
  `// x-release-please-end\n` +
  `export const PLAYWRIGHT_VERSION = '${playwrightMetadata.version}' as const;\n`;

if (checkOnly) {
  const current = await readFile(outputPath, 'utf8').catch(() => undefined);
  if (current !== generated) {
    throw new Error(
      `Generated version is stale. Run "npm run generate:version" in ${repositoryRoot}`,
    );
  }
} else {
  await writeFile(outputPath, generated, 'utf8');
}
